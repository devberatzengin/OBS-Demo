ALTER TABLE students           ADD CONSTRAINT fk_students_department        FOREIGN KEY (department_id)  REFERENCES departments (id);
ALTER TABLE students           ADD CONSTRAINT fk_students_advisor           FOREIGN KEY (advisor_id)     REFERENCES academicians (id);
ALTER TABLE courses            ADD CONSTRAINT fk_courses_department         FOREIGN KEY (department_id)  REFERENCES departments (id);
ALTER TABLE courses            ADD CONSTRAINT fk_courses_instructor         FOREIGN KEY (instructor_id)  REFERENCES academicians (id);
ALTER TABLE enrollments        ADD CONSTRAINT fk_enrollments_student        FOREIGN KEY (student_id)     REFERENCES students (id);
ALTER TABLE enrollments        ADD CONSTRAINT fk_enrollments_course         FOREIGN KEY (course_id)      REFERENCES courses (id);
ALTER TABLE enrollments        ADD CONSTRAINT fk_enrollments_semester       FOREIGN KEY (semester_id)    REFERENCES semesters (id);
ALTER TABLE exams              ADD CONSTRAINT fk_exams_course               FOREIGN KEY (course_id)      REFERENCES courses (id);
ALTER TABLE exams              ADD CONSTRAINT fk_exams_classroom            FOREIGN KEY (classroom_id)   REFERENCES classrooms (id);
ALTER TABLE exams              ADD CONSTRAINT fk_exams_semester             FOREIGN KEY (semester_id)    REFERENCES semesters (id);
ALTER TABLE grades             ADD CONSTRAINT fk_grades_enrollment          FOREIGN KEY (enrollment_id)  REFERENCES enrollments (id);
ALTER TABLE grades             ADD CONSTRAINT fk_grades_exam                FOREIGN KEY (exam_id)        REFERENCES exams (id);
ALTER TABLE attendance_records ADD CONSTRAINT fk_attendance_enrollment      FOREIGN KEY (enrollment_id)  REFERENCES enrollments (id);
ALTER TABLE schedules          ADD CONSTRAINT fk_schedules_course           FOREIGN KEY (course_id)      REFERENCES courses (id);
ALTER TABLE schedules          ADD CONSTRAINT fk_schedules_classroom        FOREIGN KEY (classroom_id)   REFERENCES classrooms (id);
ALTER TABLE office_hours       ADD CONSTRAINT fk_office_hours_academician   FOREIGN KEY (academician_id) REFERENCES academicians (id);
ALTER TABLE announcements      ADD CONSTRAINT fk_announcements_course       FOREIGN KEY (course_id)      REFERENCES courses (id);
ALTER TABLE notifications      ADD CONSTRAINT fk_notifications_user         FOREIGN KEY (user_id)        REFERENCES users (id);
ALTER TABLE chat_messages      ADD CONSTRAINT fk_chat_messages_sender       FOREIGN KEY (sender_id)      REFERENCES users (id);
ALTER TABLE chat_messages      ADD CONSTRAINT fk_chat_messages_receiver     FOREIGN KEY (receiver_id)    REFERENCES users (id);
ALTER TABLE todo_items         ADD CONSTRAINT fk_todo_items_user            FOREIGN KEY (user_id)        REFERENCES users (id);
