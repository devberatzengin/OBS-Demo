-- Baseline schema: mirrors what Hibernate generated from the JPA entities before Flyway was introduced.
-- From now on the schema changes only through new migrations (V2__..., V3__...).

CREATE TABLE faculties (
    id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    CONSTRAINT uk_faculties_name UNIQUE (name)
);

CREATE TABLE departments (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       VARCHAR(255) NOT NULL,
    faculty_id BIGINT       NOT NULL
);

CREATE TABLE classrooms (
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code     VARCHAR(255) NOT NULL,
    capacity INTEGER,
    CONSTRAINT uk_classrooms_code UNIQUE (code)
);

CREATE TABLE semesters (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                    VARCHAR(255) NOT NULL,
    start_date              DATE,
    end_date                DATE,
    exam_start_date         DATE,
    exam_end_date           DATE,
    makeup_exam_start_date  DATE,
    makeup_exam_end_date    DATE,
    registration_start_date DATE,
    registration_end_date   DATE,
    is_active               BOOLEAN NOT NULL,
    CONSTRAINT uk_semesters_name UNIQUE (name)
);

CREATE TABLE users (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username     VARCHAR(255) NOT NULL,
    password     VARCHAR(255) NOT NULL,
    email        VARCHAR(255) NOT NULL,
    first_name   VARCHAR(255) NOT NULL,
    last_name    VARCHAR(255) NOT NULL,
    role         VARCHAR(255) NOT NULL CHECK (role IN ('ADMIN', 'ACADEMICIAN', 'STUDENT', 'ADMINISTRATIVE')),
    is_active    BOOLEAN      NOT NULL,
    address      VARCHAR(255),
    phone_number VARCHAR(255),
    CONSTRAINT uk_users_username UNIQUE (username),
    CONSTRAINT uk_users_email UNIQUE (email)
);

CREATE TABLE academicians (
    id             BIGINT PRIMARY KEY,
    staff_number   VARCHAR(255) NOT NULL,
    academic_title VARCHAR(255),
    department_id  BIGINT,
    office_number  VARCHAR(255),
    birth_date     DATE,
    CONSTRAINT uk_academicians_staff_number UNIQUE (staff_number)
);

CREATE TABLE administratives (
    id            BIGINT PRIMARY KEY,
    staff_number  VARCHAR(255) NOT NULL,
    position      VARCHAR(255),
    faculty_id    BIGINT,
    department_id BIGINT,
    CONSTRAINT uk_administratives_staff_number UNIQUE (staff_number)
);

CREATE TABLE students (
    id                BIGINT PRIMARY KEY,
    student_number    VARCHAR(255) NOT NULL,
    department_id     BIGINT,
    advisor_id        BIGINT,
    current_semester  INTEGER,
    gpa               FLOAT(53),
    registration_date DATE,
    mother_name       VARCHAR(255),
    father_name       VARCHAR(255),
    birth_date        DATE,
    birth_place       VARCHAR(255),
    CONSTRAINT uk_students_student_number UNIQUE (student_number)
);

CREATE TABLE courses (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code           VARCHAR(255) NOT NULL,
    name           VARCHAR(255) NOT NULL,
    semester_level INTEGER,
    akts           INTEGER      NOT NULL,
    credits        INTEGER      NOT NULL,
    language       VARCHAR(255),
    department_id  BIGINT       NOT NULL,
    instructor_id  BIGINT,
    description    TEXT,
    syllabus       TEXT,
    open           BOOLEAN      NOT NULL,
    quota          INTEGER,
    CONSTRAINT uk_courses_code UNIQUE (code)
);

CREATE TABLE enrollments (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id  BIGINT       NOT NULL,
    course_id   BIGINT       NOT NULL,
    semester_id BIGINT       NOT NULL,
    status      VARCHAR(255) NOT NULL CHECK (status IN ('PENDING', 'APPROVED', 'REJECTED')),
    grade       VARCHAR(255),
    score       FLOAT(53)
);

CREATE TABLE exams (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    exam_type    VARCHAR(255) NOT NULL CHECK (exam_type IN ('QUIZ', 'MIDTERM', 'FINAL')),
    exam_date    TIMESTAMP(6) NOT NULL,
    ratio        FLOAT(53)    NOT NULL,
    course_id    BIGINT       NOT NULL,
    classroom_id BIGINT       NOT NULL,
    semester_id  BIGINT       NOT NULL
);

CREATE TABLE grades (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    enrollment_id BIGINT    NOT NULL,
    exam_id       BIGINT    NOT NULL,
    score         FLOAT(53) NOT NULL
);

CREATE TABLE attendance_records (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    enrollment_id   BIGINT  NOT NULL,
    attendance_date DATE    NOT NULL,
    is_present      BOOLEAN NOT NULL
);

CREATE TABLE schedules (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    day_of_week  VARCHAR(255) NOT NULL CHECK (day_of_week IN ('MONDAY', 'TUESDAY', 'WEDNESDAY', 'THURSDAY', 'FRIDAY', 'SATURDAY', 'SUNDAY')),
    start_time   TIME(6)      NOT NULL,
    end_time     TIME(6)      NOT NULL,
    course_id    BIGINT       NOT NULL,
    classroom_id BIGINT       NOT NULL
);

CREATE TABLE office_hours (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    day_of_week    VARCHAR(255) NOT NULL CHECK (day_of_week IN ('MONDAY', 'TUESDAY', 'WEDNESDAY', 'THURSDAY', 'FRIDAY', 'SATURDAY', 'SUNDAY')),
    start_time     TIME(6)      NOT NULL,
    end_time       TIME(6)      NOT NULL,
    academician_id BIGINT       NOT NULL
);

CREATE TABLE announcements (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title     VARCHAR(255)  NOT NULL,
    content   VARCHAR(2000) NOT NULL,
    timestamp TIMESTAMP(6)  NOT NULL,
    course_id BIGINT        NOT NULL
);

CREATE TABLE notifications (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id   BIGINT       NOT NULL,
    title     VARCHAR(255) NOT NULL,
    message   VARCHAR(255) NOT NULL,
    is_read   BOOLEAN      NOT NULL,
    timestamp TIMESTAMP(6)
);

CREATE TABLE chat_messages (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    content     VARCHAR(1000) NOT NULL,
    timestamp   TIMESTAMP(6)  NOT NULL,
    sender_id   BIGINT        NOT NULL,
    receiver_id BIGINT        NOT NULL,
    is_read     BOOLEAN       NOT NULL
);

CREATE TABLE system_logs (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    timestamp    TIMESTAMP(6) NOT NULL,
    action       VARCHAR(255) NOT NULL,
    details      TEXT,
    performed_by VARCHAR(255) NOT NULL,
    entity_type  VARCHAR(255),
    entity_id    VARCHAR(255)
);

CREATE TABLE todo_items (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title       VARCHAR(255) NOT NULL,
    description VARCHAR(255),
    completed   BOOLEAN      NOT NULL,
    due_date    TIMESTAMP(6),
    priority    VARCHAR(255) CHECK (priority IN ('LOW', 'MEDIUM', 'HIGH', 'CRITICAL')),
    category    VARCHAR(255) CHECK (category IN ('ACADEMIC', 'EXAM', 'MEETING', 'PERSONAL')),
    user_id     BIGINT       NOT NULL
);

